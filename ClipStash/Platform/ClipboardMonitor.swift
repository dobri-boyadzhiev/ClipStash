import AppKit
import Combine
import OSLog

/// Monitors the system clipboard for changes by polling NSPasteboard.
@MainActor
final class ClipboardMonitor: ObservableObject {
    struct PollSchedule: Equatable {
        let interval: TimeInterval
        let tolerance: TimeInterval
    }

    /// Types that password managers and other apps add to ask clipboard managers not to record
    /// the contents (https://nspasteboard.org).
    static let ignoredPasteboardTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
    ]

    @Published private(set) var isRunning = false
    
    private let logger = Logger(subsystem: "ClipStash", category: "ClipboardMonitor")
    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int = 0
    private var pollTask: Task<Void, Never>?
    private let entryManager: EntryManager
    private let settings: AppSettings
    
    /// Number of `ignoringChanges` scopes currently running.
    private var ignoreDepth = 0
    
    init(entryManager: EntryManager, settings: AppSettings, pasteboard: NSPasteboard = .general) {
        self.entryManager = entryManager
        self.settings = settings
        self.pasteboard = pasteboard
    }
    
    func start() {
        guard pollTask == nil else { return }
        lastChangeCount = pasteboard.changeCount
        isRunning = true
        pollTask = Task { @MainActor [weak self] in
            while let self = self, !Task.isCancelled {
                let interval = self.currentPollSchedule().interval
                try? await Task.sleep(nanoseconds: UInt64(interval * 1_000_000_000))
                guard !Task.isCancelled else { break }
                self.checkForChanges()
            }
        }
    }

    func stop() {
        pollTask?.cancel()
        pollTask = nil
        isRunning = false
    }
    
    /// Runs `body` without recording any pasteboard change made before it returns.
    ///
    /// ClipStash's own writes need no such scope: `PasteboardClipboardWriter` tags them with
    /// `org.nspasteboard.source`, and the monitor skips tagged contents. This is for changes
    /// ClipStash makes another app produce, such as the copy triggered by a simulated ⌘C.
    func ignoringChanges<T>(_ body: () async throws -> T) async rethrows -> T {
        ignoreDepth += 1
        defer {
            ignoreDepth -= 1
            if ignoreDepth == 0 {
                lastChangeCount = pasteboard.changeCount
            }
        }
        return try await body()
    }

    static func makePollSchedule(isPrivateMode: Bool, isLowPowerModeEnabled: Bool) -> PollSchedule {
        if isPrivateMode {
            return PollSchedule(interval: 1.2, tolerance: 0.4)
        }

        if isLowPowerModeEnabled {
            return PollSchedule(interval: 0.9, tolerance: 0.3)
        }

        return PollSchedule(interval: 0.45, tolerance: 0.15)
    }

    func currentPollSchedule() -> PollSchedule {
        Self.makePollSchedule(
            isPrivateMode: settings.isPrivateMode,
            isLowPowerModeEnabled: ProcessInfo.processInfo.isLowPowerModeEnabled
        )
    }
    
    /// Records the pasteboard contents if they changed since the last check.
    /// Returns the task that stores the new entry, if one was started.
    @discardableResult
    func checkForChanges() -> Task<Void, Never>? {
        guard ignoreDepth == 0 else { return nil }
        let currentCount = pasteboard.changeCount
        guard currentCount != lastChangeCount else { return nil }
        lastChangeCount = currentCount

        guard !settings.isPrivateMode else { return nil }
        guard !shouldIgnoreCurrentContents() else { return nil }

        let maxEntryBytes = settings.maxEntrySizeMB * 1_048_576
        let sourceBundle = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let sourceName = NSWorkspace.shared.frontmostApplication?.localizedName

        // Priority order: RTF > Text > Image > File URLs
        // (RTF also contains plain text, but we prefer the rich version)

        if let rtfData = pasteboard.data(forType: .rtf) {
            guard rtfData.count <= maxEntryBytes else {
                logger.info("Skipping RTF clipboard entry: \(rtfData.count) bytes exceeds \(maxEntryBytes) byte limit")
                return nil
            }
            // Note: NSAttributedString RTF parsing runs on main thread.
            // This is acceptable for typical clipboard RTF sizes (< 100KB).
            // For very large RTF documents this could cause brief UI stutter.
            let plainText = pasteboard.string(forType: .string)
                ?? (try? NSAttributedString(
                    data: rtfData,
                    options: [.documentType: NSAttributedString.DocumentType.rtf],
                    documentAttributes: nil
                ).string)
                ?? ""
            guard !plainText.isEmpty else { return nil }
            return Task {
                await entryManager.processNewRTF(plainText: plainText, rtfData: rtfData, source: sourceBundle, sourceName: sourceName)
            }
        } else if let string = pasteboard.string(forType: .string) {
            guard string.utf8.count <= maxEntryBytes else {
                logger.info("Skipping text clipboard entry: \(string.utf8.count) bytes exceeds \(maxEntryBytes) byte limit")
                return nil
            }
            return Task {
                await entryManager.processNewText(string, source: sourceBundle, sourceName: sourceName)
            }
        } else if let imgData = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            guard imgData.count <= maxEntryBytes else {
                logger.info("Skipping image clipboard entry: \(imgData.count) bytes exceeds \(maxEntryBytes) byte limit")
                return nil
            }
            return Task {
                await entryManager.processNewImage(imgData, source: sourceBundle, sourceName: sourceName)
            }
        } else if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            return Task {
                await entryManager.processNewFileURLs(paths, source: sourceBundle, sourceName: sourceName)
            }
        }
        return nil
    }

    /// Whether ClipStash wrote the current contents itself, or their writer marked them as
    /// concealed or transient (e.g. a password copied from a password manager).
    private func shouldIgnoreCurrentContents() -> Bool {
        if pasteboard.string(forType: .nspasteboardSource) == PasteboardClipboardWriter.sourceIdentifier {
            return true
        }
        let types = pasteboard.types ?? []
        return types.contains { Self.ignoredPasteboardTypes.contains($0) }
    }
}
